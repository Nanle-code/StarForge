//! AI-assisted community analytics for the template marketplace.
//!
//! Resolves issue #532 ("AI Template Community Analysis") by aggregating
//! signals about how marketplace templates are actually used and received:
//!
//! - **Usage analytics** — locally logged scaffold/install/update events,
//!   combined with lifetime download counts from the registry.
//! - **Feedback analysis** — locally submitted ratings/comments
//!   (`starforge template feedback`), summarised into sentiment and common
//!   issue keywords.
//! - **Trend identification** — rising vs. declining templates, computed by
//!   comparing usage activity across two adjacent time windows.
//! - **Issue detection** — templates flagged for missing docs, deprecated
//!   maintenance status, unresolved security findings, malformed
//!   compatibility metadata, or a cluster of bug reports.
//! - **Improvement suggestions** — a rule-based engine that turns the above
//!   signals into concrete, actionable next steps.
//! - **Community insights** — cross-template rollups such as tag popularity
//!   and top contributing authors.
//!
//! An optional narrative summary can be generated by a locally running
//! Ollama model (see [`ai_narrative_summary`]); this is best-effort and the
//! deterministic report is always available even when Ollama is not
//! installed or not running.

